"""Generate a small photo library full of the awkward cases the scanner must handle.

Usable from tests and by hand:  uv run python tests/samplelib.py /tmp/sample-drive
"""

from __future__ import annotations

import io
import random
import shutil
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

DATE_TAG = 0x9003  # DateTimeOriginal (Exif sub-IFD)
EXIF_IFD = 0x8769


def picture(seed: int, size=(1600, 1200)) -> Image.Image:
    """A distinct, photo-like image: gradient plus random shapes."""
    rng = random.Random(seed)
    w, h = size
    x = np.linspace(0, 1, w)[None, :, None]
    y = np.linspace(0, 1, h)[:, None, None]
    base = np.array([rng.random(), rng.random(), rng.random()])[None, None, :]
    arr = (255 * np.clip(base * 0.5 + x * rng.random() * 0.5 + y * rng.random() * 0.4, 0, 1)).astype(np.uint8)
    img = Image.fromarray(np.ascontiguousarray(np.broadcast_to(arr, (h, w, 3))))
    draw = ImageDraw.Draw(img)
    for _ in range(12):
        x0, y0 = rng.randrange(w), rng.randrange(h)
        x1, y1 = x0 + rng.randrange(50, w // 2), y0 + rng.randrange(50, h // 2)
        color = tuple(rng.randrange(256) for _ in range(3))
        (draw.ellipse if rng.random() < 0.5 else draw.rectangle)((x0, y0, x1, y1), fill=color)
    return img


def save_jpeg(img: Image.Image, path: Path, camera=True, date="2004:07:21 13:05:09", quality=90) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    exif = Image.Exif()
    if camera:
        exif[0x010F] = "Canon"
        exif[0x0110] = "Canon EOS 10D"
        exif.get_ifd(EXIF_IFD)[DATE_TAG] = date
    img.save(path, "JPEG", quality=quality, exif=exif)
    return path


def build(root: Path) -> dict[str, Path]:
    """Create the sample library under ``root`` and return named paths of interest."""
    root = Path(root)
    if root.exists():
        shutil.rmtree(root)
    p: dict[str, Path] = {}

    for i in range(1, 7):
        p[f"photo{i}"] = save_jpeg(picture(i), root / "photos/2004" / f"IMG_{i:04d}.jpg",
                                   date=f"2004:07:{i:02d} 10:00:00")
    # Exact duplicates in a backup folder.
    for i in (1, 2, 3):
        dst = root / "backup/old pc/2004" / f"IMG_{i:04d}.jpg"
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p[f"photo{i}"], dst)
        p[f"dup{i}"] = dst

    # Thumbnails generated by "old software": small, no EXIF, cache-style folders.
    for i in (1, 2):
        thumb = picture(i).copy()
        thumb.thumbnail((160, 160))
        p[f"thumb{i}"] = save_jpeg(thumb, root / "photos/2004/.thumbnails" / f"IMG_{i:04d}_thumb.jpg", camera=False)
    # An orphan thumbnail whose original is gone.
    lost = picture(99)
    lost.thumbnail((160, 160))
    p["orphan_thumb"] = save_jpeg(lost, root / "web/thumbs/tn_beach.jpg", camera=False)

    # Damaged files.
    good = p["photo4"].read_bytes()
    p["truncated"] = root / "broken/IMG_trunc.jpg"
    p["truncated"].parent.mkdir(parents=True, exist_ok=True)
    p["truncated"].write_bytes(good[: len(good) * 6 // 10])
    mid = len(good) // 2  # a block of zeros, as left by a bad sector or failed copy
    p["zeroed"] = root / "broken/IMG_zeroed.jpg"
    p["zeroed"].write_bytes(good[:mid] + b"\0" * 4096 + good[mid + 4096:])
    p["empty"] = root / "broken/empty.jpg"
    p["empty"].write_bytes(b"")
    p["garbage_raw"] = root / "broken/IMG_9999.CR2"
    p["garbage_raw"].write_bytes(random.Random(7).randbytes(300_000))
    grey = picture(5)
    ImageDraw.Draw(grey).rectangle((0, 900, 1600, 1200), fill=(128, 128, 128))
    p["grey_band"] = save_jpeg(grey, root / "broken/IMG_greyband.jpg", quality=95)

    # Other formats.
    import pillow_heif

    pillow_heif.register_heif_opener()
    p["heic"] = root / "phone/IMG_1000.HEIC"
    p["heic"].parent.mkdir(parents=True, exist_ok=True)
    picture(20, (800, 600)).save(p["heic"], "HEIF", quality=80)

    p["tiff16"] = root / "scans/scan_16bit.tif"
    p["tiff16"].parent.mkdir(parents=True, exist_ok=True)
    ramp = (np.linspace(0, 65535, 400 * 300).reshape(300, 400)).astype(np.uint16)
    Image.fromarray(ramp).save(p["tiff16"])

    from psd_tools import PSDImage

    p["psd"] = root / "edits/collage.psd"
    p["psd"].parent.mkdir(parents=True, exist_ok=True)
    PSDImage.frompil(picture(30, (640, 480))).save(p["psd"])

    p["png"] = root / "edits/screenshot.png"
    picture(31, (500, 400)).save(p["png"])

    p["video"] = root / "videos/clip.mp4"
    p["video"].parent.mkdir(parents=True, exist_ok=True)
    _write_video(p["video"])

    # Ignored: not media, and the trash.
    (root / "notes.txt").write_text("not an image")
    trash = root / "$RECYCLE.BIN/IMG_0001.jpg"
    trash.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(p["photo1"], trash)
    return p


def _write_video(path: Path, frames: int = 48) -> None:
    import av

    with av.open(str(path), "w") as container:
        stream = container.add_stream("mpeg4", rate=24)
        stream.width, stream.height, stream.pix_fmt = 320, 240, "yuv420p"
        for i in range(frames):
            img = picture(40 + i // 16, (320, 240))
            for packet in stream.encode(av.VideoFrame.from_image(img)):
                container.mux(packet)
        for packet in stream.encode():
            container.mux(packet)


def jpeg_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=90)
    return buf.getvalue()


if __name__ == "__main__":
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "sample-drive")
    paths = build(target)
    print(f"Built sample library with {len(paths)} notable files at {target.resolve()}")
